def fetch_company_info_bocha(company_name, bocha_key):
    """改用博查搜索获取企业基本公开信息"""
    if not bocha_key: return "未配置博查Key，无法搜索公开信息"
    try:
        query = f"{company_name} 公司简介 主营业务 风险"
        res = requests.post(
            "https://api.bocha.cn/v1/web-search", 
            headers={"Authorization": f"Bearer {bocha_key}", "Content-Type": "application/json"},
            json={"query": query, "count": 3, "summary": True}, 
            timeout=12
        )
        if res.status_code == 200:
            data = res.json()
            summaries = ""
            if "data" in data and "webPages" in data["data"]:
                for page in data["data"]["webPages"]["value"]:
                    summaries += f"- {page.get('summary', '')}\n"
            return summaries if summaries else "全网未搜索到该公司的公开简介。"
    except Exception as e:
        return f"搜索失败: {str(e)}"

